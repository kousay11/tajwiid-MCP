#!/usr/bin/env python3
"""Run every tool through a real stdio MCP client and write a transcript (markdown).

Book text is never written: page text and search snippets are replaced by lengths/hashes.
Usage: e2e_report.py --source-root /path/to/wirdi-Ai --out docs/E2E_REPORT.md
"""

import argparse
import asyncio
import json
import sys
import time
from pathlib import Path

from mcp import Client, StdioServerParameters

ROOT = Path(__file__).resolve().parents[1]
QALOUN = {
    "corpus_id": "wirdi-ai:quranpedia:qalun",
    "corpus_version": "sha256:ece0a2b0efe44d496211c595d0a34f495413bc93f78fba8095a666e2048d1303",
    "numbering_system": "wirdi-ai:qalun-6214",
    "riwaya": "qaloun",
    "tariq": "unspecified",
}


def selection(surah, first, last):
    return {"start": {**QALOUN, "surah": surah, "ayah": first}, "end_ayah": last}


def redact(value):
    """Keep the shape of a result but drop any source-book text."""
    if isinstance(value, dict):
        out = {}
        for key, item in value.items():
            if (
                key == "text"
                and isinstance(item, str)
                and ("text_quality" in value or "text_sha256" in value)
            ):
                out[key] = f"<{len(item)} characters withheld>"
            elif key == "snippet":
                out[key] = "<withheld>"
            else:
                out[key] = redact(item)
        return out
    if isinstance(value, list):
        return [redact(v) for v in value]
    return value


def shorten(payload, limit=1800):
    text = json.dumps(redact(payload), ensure_ascii=False, indent=1)
    if len(text) > limit:
        text = text[:limit] + f"\n... ({len(text) - limit} more characters)"
    return text


async def run(source_root: str, out: Path) -> None:
    params = StdioServerParameters(
        command=sys.executable,
        args=["-m", "wirdi_mcp.server"],
        cwd=ROOT,
        env={"WIRDI_MCP_LOG_LEVEL": "ERROR", "WIRDI_AI_ROOT": source_root},
    )
    waqf, wasl = {"mode": "waqf"}, {"mode": "wasl"}
    calls = [
        ("health_check", {}),
        ("list_tajwid_rules", {}),
        ("get_tajwid_rule", {"rule_id": "qalqala_kubra", "version": "1"}),
        ("get_qaloun_passage", {"selection": selection(18, 45, 52)}),
        (
            "analyze_qaloun_tajwid",
            {"selection": selection(18, 45, 52), "reading_context": waqf, "limit": 4},
        ),
        (
            "analyze_qaloun_tajwid",
            {"selection": selection(18, 45, 52), "reading_context": wasl, "limit": 2},
        ),
        (
            "analyze_qaloun_tajwid",
            {
                "selection": selection(112, 1, 4),
                "reading_context": waqf,
                "rule_ids": ["qalqala_kubra"],
            },
        ),
        (
            "analyze_qaloun_tajwid",
            {
                "selection": selection(2, 1, 40),
                "reading_context": waqf,
                "families": ["lam_taarif"],
                "limit": 3,
            },
        ),
        ("summarize_tajwid", {"surah": 18, "reading_context": waqf, "limit": 3}),
        ("analyze_app_page", {"page": 263, "reading_context": waqf, "limit": 3}),
        (
            "get_tajwid_explanation",
            {"annotation_id": "lam_qamariya:1:18:45:3-5:waqf", "annotation_version": "1.0.0"},
        ),
        ("get_source_page", {"edition_id": "book-a-2010", "page_start": 44, "page_end": 44}),
        ("search_source_pages", {"query": "القلقلة", "edition_ids": ["book-a-2010"], "limit": 5}),
        (
            "analyze_qaloun_tajwid",
            {
                "selection": selection(18, 45, 52),
                "reading_context": waqf,
                "rule_ids": ["no_such_rule"],
            },
        ),
        ("summarize_tajwid", {"surah": 0, "reading_context": waqf}),
    ]
    lines = [
        "# End-to-end report",
        "",
        "Real stdio MCP client (`mcp.Client`) against `python -m wirdi_mcp.server` with the real",
        "Wirdi AI source files. Generated by `scripts/e2e_report.py`; large results are shortened",
        "and no source-book or Quran text is written. Reading context is waqf unless stated.",
        "",
    ]
    failures = 0
    async with Client(params, read_timeout_seconds=30) as client:
        info = client.server_info
        tools = (await client.list_tools()).tools
        lines += [
            f"Server `{info.name}` {info.version}; {len(tools)} tools: "
            + ", ".join(f"`{t.name}`" for t in tools),
            "",
        ]
        for tool, args in calls:
            started = time.perf_counter()
            result = await client.call_tool(tool, args)
            elapsed = (time.perf_counter() - started) * 1000
            payload = result.structured_content
            status = "error" if result.is_error else "ok"
            expected_error = (
                tool in {"get_tajwid_explanation"}
                or args.get("rule_ids") == ["no_such_rule"]
                or args.get("surah") == 0
            )
            if result.is_error != expected_error and not (
                tool in {"get_source_page", "search_source_pages"} and result.is_error
            ):
                failures += 1
            detail = payload["error"]["code"] if result.is_error else payload["validation_status"]
            lines += [
                f"## `{tool}` ({status}: {detail}, {elapsed:.0f} ms)",
                "",
                "Arguments: `" + json.dumps(redact(args), ensure_ascii=False)[:300] + "`",
                "",
                "```json",
                shorten(payload),
                "```",
                "",
            ]
    lines.append(f"Unexpected outcomes: {failures}.")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}; unexpected outcomes: {failures}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", required=True)
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "E2E_REPORT.md")
    args = parser.parse_args()
    asyncio.run(run(args.source_root, args.out))
